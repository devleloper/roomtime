#!/usr/bin/env python3
"""Builds every RoomTime brand asset from a hand-authored mark.

Usage (macOS, Xcode command line tools; standard library only):

    python3 assets/brand/tool/build.py            # option C (chosen, default)
    python3 assets/brand/tool/build.py --mark B   # rejected option B
    python3 assets/brand/tool/build.py --mark A   # reference option A

Inputs:
  src/marks/roomtime-mark-{a,b,c}.svg   hand-authored master geometry
  ../fonts/inter/InterVariable.ttf      wordmark typeface (SIL OFL 1.1)
Outputs (for the chosen mark):
  src/*.svg                             generated vector masters
  icon/**.png, splash/*.png, logo/*.png platform rasters
  docs/design/img/logo-sheet.png, icon-sheet.png
Always (all three marks, independent of --mark):
  docs/design/img/icon-options.png      comparison sheet B / C (+ A reference)

Rasterisation uses macOS CoreSVG through tool/render.swift; the wordmark is
set in Inter Bold and converted to outlines through CoreText
(tool/outline.swift), so no SVG depends on an installed font. No network
access, no third-party packages.

Switching the mark also needs the in-app painter: see the "Switching marks"
note in docs/design/identity.md (room_time_logo.dart paints option C).
"""

