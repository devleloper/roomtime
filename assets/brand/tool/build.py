# Brand colors. Keep in sync with lib/presentation/theme/app_palette.dart.
BLUE = '#00AEFF'  # RoomTime Blue: icon tiles, mark on dark surfaces
BLUE_55 = '#0083C3'  # mark on light surfaces (3.97:1 on Paper, 3.22:1 on #E1E2E4)
TILE_TOP = BLUE  # icon gradient, top: the brand color itself
TILE_BOTTOM = '#0695DB'  # icon gradient, bottom (OKLCH L .64, hue 240)
INK = '#001D2F'  # wordmark on light backgrounds
WHITE = '#FFFFFF'
PAPER = '#F9F9FB'  # light surface
NIGHT = '#121212'  # dark surface
DOORLIGHT = '#FFB164'  # UI accent (not used inside the mark)

# Per-mark metrics on the 96-unit grid.
#   centre  visual centre used for every icon placement
#   reach   farthest outline point from the centre (Android/maskable safe
#           circles)
#   body    lockup box (left, top, right, bottom); the lockup viewBox runs to
#           `bottom` (A's tail hangs below the body)
#   icon    scale on the 1024 px app icon (px per unit)
#   cap     wordmark cap height in the lockup (units)
MARKS = {
    'A': dict(name='Open door', centre=(47, 52), reach=56.22,
              body=(12, 10, 84, 86), bottom=96, icon=7.2, cap=38),
    'B': dict(name='Doorway R', centre=(48, 48), reach=50.25,
              body=(14, 11, 82, 85), bottom=85, icon=6.7, cap=37),
    'C': dict(name='Door swing', centre=(48, 48), reach=43.62,
              body=(13, 22, 83, 74), bottom=74, icon=7.4, cap=30),
}
WORD = 'RoomTime'
WORD_WEIGHT = 700
WORD_TRACKING = -0.02
LOCKUP_GAP = 16  # units between the mark body and the R of the wordmark


def read_mark(key):
    path = os.path.join(MARKS_DIR, f'roomtime-mark-{key.lower()}.svg')
    svg_text = open(path).read()
    return re.search(r'<path id="mark"[^>]*\sd="([^"]+)"', svg_text).group(1)


def svg(w, h, body, view=None, title='RoomTime', key='B'):
    view = view or f'0 0 {w} {h}'
    # No double hyphen inside an XML comment: "mark B", not "--mark B".
    header = (f'<!-- Generated by assets/brand/tool/build.py (mark {key}) '
              f'from marks/roomtime-mark-{key.lower()}.svg. Do not edit by hand. -->')
    return (f'<svg xmlns="http://www.w3.org/2000/svg" '
            f'xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="{view}" '
            f'width="{w}" height="{h}">\n  {header}\n  <title>{title}</title>\n'
            f'{body}</svg>\n')


class Mark:
    def __init__(self, key):
        self.key = key
        self.d = read_mark(key)
        for k, v in MARKS[key].items():
            setattr(self, k, v)

    def path(self, color):
        """The mark in its own 96-unit coordinates; cut-outs are holes."""
        return f'<path fill="{color}" fill-rule="evenodd" d="{self.d}"/>'

    def placed(self, cx, cy, scale, color):
        """Places the mark so its visual centre lands on (cx, cy)."""
        mx, my = self.centre
        tx, ty = cx - mx * scale, cy - my * scale
        return (f'  <g transform="translate({tx:.3f} {ty:.3f}) scale({scale:.4f})">'
                f'{self.path(color)}</g>\n')


def gradient(gid='bg'):
    return (f'  <defs><linearGradient id="{gid}" x1="0" y1="0" x2="0" y2="1">'
            f'<stop offset="0" stop-color="{TILE_TOP}"/>'
            f'<stop offset="1" stop-color="{TILE_BOTTOM}"/>'
            f'</linearGradient></defs>\n')


# ---------------------------------------------------------------- tools

def compile_tools(tmp):
    out = {}
    for name in ('render', 'outline'):
        exe = os.path.join(tmp, name)
        subprocess.run(['swiftc', '-O', os.path.join(TOOL, f'{name}.swift'),
                        '-o', exe], check=True)
        out[name] = exe
    return out


def wordmark(tools, size):
    """Inter outlines for WORD at font size `size`, baseline y=0."""
    res = subprocess.run([tools['outline'], FONT, WORD, str(WORD_WEIGHT),
                          str(size), str(WORD_TRACKING)],
                         check=True, capture_output=True, text=True)
    data = json.loads(res.stdout)
    d = ' '.join(p for g in data['glyphs'] for p in g['subpaths'])
    first = data['glyphs'][0]['bbox'][0]
    last = data['glyphs'][-1]['bbox'][2]
    return d, first, last, data['capHeight']


def render(tools, src, dst, w, h, opaque=False):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    args = [tools['render'], src, dst, str(w), str(h)]
    if opaque:
        args.append('opaque')
    subprocess.run(args, check=True)


def png_info(path):
    with open(path, 'rb') as f:
        head = f.read(33)
    w, h, depth, ctype = struct.unpack('>IIBB', head[16:26])
    return w, h, {2: 'RGB', 6: 'RGBA'}.get(ctype, str(ctype))


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(text)


# ---------------------------------------------------------------- masters

def lockup(tools, m):
    """Wordmark outlines and placement for mark `m`: (d, x0, baseline, view, vw, vh)."""
    left, top, right, bottom = m.body
    probe = wordmark(tools, 100)
    size = m.cap / probe[3] * 100
    d, first, last, cap = wordmark(tools, size)
    x0 = right + LOCKUP_GAP - first
    baseline = (top + bottom) / 2 + cap / 2
    vw = x0 + last - left
    vh = m.bottom - top
    return d, x0, baseline, f'{left} {top} {vw:.2f} {vh}', vw, vh


def build_svgs(tools, m):
    """Vector masters for mark `m`. Returns {name: svg text}, lockup size."""
    out = {}
    k = m.key
    out['mark'] = svg(96, 96, '  ' + m.path(BLUE) + '\n', key=k)
    out['mark-mono'] = svg(96, 96, '  ' + m.path('#000000') + '\n', key=k)

    d, x0, baseline, view, vw, vh = lockup(tools, m)
    word = lambda ink: (f'  <path fill="{ink}" transform="translate({x0:.3f} {baseline:.3f})" '
                        f'd="{d}"/>\n')
    for name, mark_color, ink in (('logo-light', BLUE_55, INK),
                                  ('logo-dark', BLUE, WHITE),
                                  ('logo-mono', '#000000', '#000000')):
        out[name] = svg(round(vw * 4), round(vh * 4),
                        '  ' + m.path(mark_color) + '\n' + word(ink), view=view, key=k)

    # App icon, 1024, full bleed (iOS and stores apply the mask).
    out['app-icon'] = svg(1024, 1024,
                          gradient() + '  <rect width="1024" height="1024" fill="url(#bg)"/>\n'
                          + m.placed(512, 512, m.icon, WHITE), key=k)

    # Android adaptive icon, 108 dp at 4x = 432 px; 72 dp (288 px) visible.
    # The mark keeps its iOS share of the visible tile (+10 % for the circle
    # mask) and must stay inside the 66 dp safe circle (r 132 px).
    s = min(m.icon * 288 / 1024 * 1.1, 128 / m.reach)
    out['adaptive-foreground'] = svg(432, 432, m.placed(216, 216, s, WHITE), key=k)
    out['adaptive-background'] = svg(432, 432, gradient() +
                                     '  <rect width="432" height="432" fill="url(#bg)"/>\n', key=k)
    out['adaptive-monochrome'] = svg(432, 432, m.placed(216, 216, s, WHITE), key=k)

    # macOS: 824 px rounded square on a 1024 canvas, 185 px corners, soft
    # shadow (Apple macOS icon grid).
    out['macos-icon'] = svg(1024, 1024,
                            gradient() +
                            '  <defs><filter id="sh" x="-10%" y="-10%" width="120%" height="130%">'
                            '<feGaussianBlur stdDeviation="14"/></filter></defs>\n'
                            '  <rect x="100" y="112" width="824" height="824" rx="185" '
                            'fill="#000000" opacity="0.28" filter="url(#sh)"/>\n'
                            '  <rect x="100" y="100" width="824" height="824" rx="185" fill="url(#bg)"/>\n'
                            + m.placed(512, 512, m.icon * 824 / 1024, WHITE), key=k)

    # Web "any" icon: rounded tile on transparent, 512 artboard.
    out['web-icon'] = svg(512, 512,
                          gradient() + '  <rect width="512" height="512" rx="115" fill="url(#bg)"/>\n'
                          + m.placed(256, 256, m.icon / 2, WHITE), key=k)
    # Web maskable: full bleed, mark inside the 80 % safe circle (r 204.8).
    sm = min(m.icon / 2 * 1.1, 200 / m.reach)
    out['web-maskable'] = svg(512, 512,
                              gradient() + '  <rect width="512" height="512" fill="url(#bg)"/>\n'
                              + m.placed(256, 256, sm, WHITE), key=k)
    # Favicon: the app tile, mark enlarged for 16 and 32 px.
    out['favicon'] = svg(32, 32,
                         gradient() + '  <rect width="32" height="32" rx="7" fill="url(#bg)"/>\n'
                         + m.placed(16, 16, m.icon / 32 * 1.12, WHITE), key=k)

    # Splash: the mark in the color for each background (>= 3:1).
    # flutter_native_splash `image`: 4x density, 128 dp -> 512 px.
    # Android 12+ icon without background: 1152 px, content inside the
    # 768 px circle (r 384); the mark reaches r 340.
    for name, color in (('light', BLUE_55), ('dark', BLUE)):
        out[f'splash-mark-{name}'] = svg(512, 512, m.placed(256, 256, 4.4 * m.icon / 7.2, color), key=k)
        out[f'splash-android12-{name}'] = svg(1152, 1152,
                                              m.placed(576, 576, min(340 / m.reach, 4.4 * m.icon / 7.2 * 2.25), color), key=k)

    paths = {}
    for name, text in out.items():
        fname = 'favicon.svg' if name == 'favicon' else f'roomtime-{name}.svg'
        paths[name] = os.path.join(SRC, fname)
        write(paths[name], text)
    return paths, (vw, vh)


