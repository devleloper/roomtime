def build_pngs(tools, src, logo_size):
    jobs = [
        ('app-icon', 'icon/app-icon-1024.png', 1024, 1024, True),
        ('adaptive-foreground', 'icon/android/adaptive-foreground-432.png', 432, 432, False),
        ('adaptive-background', 'icon/android/adaptive-background-432.png', 432, 432, True),
        ('adaptive-monochrome', 'icon/android/adaptive-monochrome-432.png', 432, 432, False),
        ('macos-icon', 'icon/macos/macos-icon-1024.png', 1024, 1024, False),
        ('web-icon', 'icon/web/icon-192.png', 192, 192, False),
        ('web-icon', 'icon/web/icon-512.png', 512, 512, False),
        ('web-maskable', 'icon/web/icon-maskable-192.png', 192, 192, True),
        ('web-maskable', 'icon/web/icon-maskable-512.png', 512, 512, True),
        ('app-icon', 'icon/web/apple-touch-icon-180.png', 180, 180, True),
        ('favicon', 'icon/web/favicon-16.png', 16, 16, False),
        ('favicon', 'icon/web/favicon-32.png', 32, 32, False),
        ('splash-mark-light', 'splash/splash-mark-light-512.png', 512, 512, False),
        ('splash-mark-dark', 'splash/splash-mark-dark-512.png', 512, 512, False),
        ('splash-android12-light', 'splash/splash-android12-light-1152.png', 1152, 1152, False),
        ('splash-android12-dark', 'splash/splash-android12-dark-1152.png', 1152, 1152, False),
    ]
    vw, vh = logo_size
    for name in ('logo-light', 'logo-dark'):
        jobs.append((name, f'logo/{name}-1200.png', 1200, round(1200 * vh / vw), False))
    jobs.append(('mark-mono', 'logo/mark-mono-512.png', 512, 512, False))
    results = []
    for name, rel, w, h, opaque in jobs:
        dst = os.path.join(BRAND, rel)
        render(tools, src[name], dst, w, h, opaque)
        results.append((rel, *png_info(dst)))
    return results


