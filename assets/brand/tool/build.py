def build_option_svgs(tools, m, out_dir):
    """Same masters as build_svgs, written to a scratch dir (comparison only)."""
    global SRC
    saved = SRC
    SRC = out_dir
    try:
        return build_svgs(tools, m)
    finally:
        SRC = saved


