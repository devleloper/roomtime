def label(x, y, text, fill, size=14, anchor='start', weight='normal'):
    return (f'  <text x="{x}" y="{y}" font-family="Helvetica" font-size="{size}" '
            f'font-weight="{weight}" fill="{fill}" text-anchor="{anchor}">{text}</text>\n')


_nest = [0]


def nested(path, x, y, w, h=None):
    """Embeds a generated SVG file at (x, y), width w; ids are made unique."""
    text = open(path).read()
    view = re.search(r'viewBox="([^"]+)"', text).group(1)
    body = re.sub(r'^.*?<title>[^<]*</title>\n', '', text, flags=re.S).replace('</svg>\n', '')
    if h is None:
        _, _, vw, vh = map(float, view.split())
        h = w * vh / vw
    _nest[0] += 1
    p = f'n{_nest[0]}'
    for i in ('bg', 'sh'):
        body = body.replace(f'id="{i}"', f'id="{p}{i}"').replace(f'url(#{i})', f'url(#{p}{i})')
    return (f'  <svg x="{x}" y="{y}" width="{w}" height="{h:.2f}" viewBox="{view}">\n'
            f'{body}  </svg>\n')


def raster(path, x, y, w, h=None):
    """Embeds a PNG (used to show true 16/32 px rasters, also enlarged)."""
    data = base64.b64encode(open(path, 'rb').read()).decode()
    return (f'  <image x="{x}" y="{y}" width="{w}" height="{h or w}" '
            f'xlink:href="data:image/png;base64,{data}"/>\n')


def recolor(path, frm, to):
    return open(path).read().replace(frm, to)


def logo_sheet(tools, m, src, tmp):
    W, H = 1600, 900
    parts = []
    panels = ((PAPER, INK, '#42474E', 'logo-light', BLUE_55, 'Light background'),
              (NIGHT, WHITE, '#AAAAAA', 'logo-dark', BLUE, 'Dark background'))
    for i, (bg, fg, sub, logo, mark_color, title) in enumerate(panels):
        x0 = i * 800
        parts.append(f'  <rect x="{x0}" y="0" width="800" height="{H}" fill="{bg}"/>\n')
        parts.append(label(x0 + 48, 56, f'{title} · mark {m.key} "{m.name}"', sub, 18))
        parts.append(nested(src[logo], x0 + 48, 110, 520))
        x = x0 + 48
        mark_svg = os.path.join(tmp, f'mark-{i}.svg')
        write(mark_svg, recolor(src['mark'], BLUE, mark_color))
        for size in (128, 64, 48, 32, 24, 16):
            parts.append(nested(mark_svg, x, 380 + (128 - size), size, size))
            parts.append(label(x + size / 2, 540, f'{size}', sub, 13, 'middle'))
            x += size + 36
        mono_svg = os.path.join(tmp, f'mono-{i}.svg')
        write(mono_svg, recolor(src['mark-mono'], '#000000', INK if i == 0 else WHITE))
        parts.append(nested(mono_svg, x0 + 600, 380, 128, 128))
        parts.append(label(x0 + 664, 540, 'one color', sub, 13, 'middle'))
        sw = [(BLUE, 'Blue #00AEFF'), (BLUE_55, 'Blue 55 #0083C3'),
              ('#006A9E', 'Blue 40 #006A9E'), (INK, 'Ink #001D2F')]
        for k, (c, name) in enumerate(sw):
            sx = x0 + 48 + k * 180
            parts.append(f'  <rect x="{sx}" y="600" width="156" height="156" rx="20" fill="{c}" '
                         f'stroke="{sub}" stroke-opacity="0.35"/>\n')
            parts.append(label(sx, 786, name, fg, 14))
        note = ('Mark Blue 55 on light (3.97:1), ink wordmark 16.41:1' if i == 0 else
                'Mark Blue #00AEFF on dark (7.58:1), white wordmark 18.73:1')
        parts.append(label(x0 + 48, 850, note, sub, 14))
    path = os.path.join(tmp, 'logo-sheet.svg')
    write(path, svg(W, H, ''.join(parts), title='RoomTime logo sheet', key=m.key))
    render(tools, path, os.path.join(DOCS_IMG, 'logo-sheet.png'), W, H, True)


